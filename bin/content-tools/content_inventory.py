#!/usr/bin/env python3
"""content_inventory — regenerate a conversion-manifest.json from any WP DB.

Python 3 stdlib only. Two steps, because the DB lives inside the WP container:

  1) `content_inventory.py gen-dump [--config CFG]`
        prints a PHP dump script to stdout. Run it against the site:

          python3 content_inventory.py gen-dump > /tmp/dump.php
          docker compose cp /tmp/dump.php wordpress:/tmp/dump.php
          docker compose exec -T wordpress wp eval-file /tmp/dump.php \
              /tmp/content-inventory-raw.json --allow-root
          docker compose cp wordpress:/tmp/content-inventory-raw.json ./raw.json

        The dump is READ-ONLY: it only reads posts/postmeta and writes a JSON
        file inside the container.

  2) `content_inventory.py build --raw raw.json [--config CFG] [--out manifest.json]`
        classifies every item (engine detection matching the headless API /
        verify-content order; DIVI module analysis; markdown-vs-gutenberg target
        per the complexity rules) and writes conversion-manifest.json in the
        canonical schema (summary + items[]).

Engine detection order (identical to bin/verify-content.php / headless API):
  _headless_engine override -> markdown (flag+filtered) -> wp: -> et_pb_ ->
  empty -> html. So the same tool inventories a fresh DIVI DB and a
  post-conversion (markdown/gutenberg) DB.
"""
from __future__ import annotations
import argparse
import datetime
import json
import re
import sys

try:
    import ct_common
except ImportError:
    import os
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import ct_common


# --------------------------------------------------------------------------
# 1) PHP dump generator
# --------------------------------------------------------------------------
PHP_TEMPLATE = r"""<?php
/**
 * content-inventory dump — READ-ONLY. Generated by content_inventory.py.
 * Writes raw per-post fields as JSON for offline classification.
 * Usage: wp eval-file dump.php /tmp/content-inventory-raw.json --allow-root
 */
$out_path = (isset($args) && !empty($args[0])) ? $args[0] : '/tmp/content-inventory-raw.json';
$post_types = %POST_TYPES%;
$statuses   = %STATUSES%;

global $shortcode_tags;
$registered = array_keys($shortcode_tags);

$items = array();
foreach ($post_types as $pt) {
  $q = new WP_Query(array(
    'post_type' => $pt,
    'post_status' => $statuses,
    'posts_per_page' => -1,
    'orderby' => 'ID',
    'order' => 'ASC',
    'no_found_rows' => true,
    'suppress_filters' => true,
  ));
  foreach ($q->posts as $p) {
    $items[] = array(
      'id' => (int)$p->ID,
      'post_type' => $pt,
      'status' => $p->post_status,
      'slug' => $p->post_name,
      'title' => $p->post_title,
      'url_path' => parse_url(get_permalink($p), PHP_URL_PATH),
      'content' => $p->post_content,
      'content_filtered' => $p->post_content_filtered,
      'markdown_enabled' => (string)get_post_meta($p->ID, '_markdown_enabled', true),
      'headless_engine' => (string)get_post_meta($p->ID, '_headless_engine', true),
    );
  }
  wp_reset_postdata();
}
$payload = array('registered_shortcodes' => $registered, 'items' => $items);
file_put_contents($out_path, json_encode($payload, JSON_UNESCAPED_UNICODE|JSON_UNESCAPED_SLASHES));
echo "WROTE ".count($items)." items to ".$out_path."\n";
"""


def gen_dump(cfg):
    inv = cfg["inventory"]
    php = PHP_TEMPLATE
    php = php.replace("%POST_TYPES%", _php_array(inv["post_types"]))
    php = php.replace("%STATUSES%", _php_array(inv["statuses"]))
    return php


def _php_array(items):
    return "array(" + ", ".join("'%s'" % str(i).replace("'", "\\'") for i in items) + ")"


# --------------------------------------------------------------------------
# 2) classification
# --------------------------------------------------------------------------
def detect_engine(item):
    content = item.get("content", "") or ""
    filtered = item.get("content_filtered", "") or ""
    override = item.get("headless_engine", "") or ""
    md_flag = item.get("markdown_enabled", "") or ""
    if override:
        return override
    if md_flag == "1" and filtered.strip() != "":
        return "markdown"
    if "<!-- wp:" in content:
        return "gutenberg"
    if "[et_pb_" in content:
        return "divi"
    if content.strip() == "":
        return "empty"
    return "html"


def analyze_divi(content):
    counts = {}
    for m in re.finditer(r"\[et_pb_([a-z0-9_]+)", content, re.I):
        name = m.group(1).lower()
        counts[name] = counts.get(name, 0) + 1
    n_sections = counts.get("section", 0)
    n_rows = counts.get("row", 0) + counts.get("row_inner", 0)
    max_cols = 0
    for rowblock in re.findall(r"\[et_pb_row(?:_inner)?\b.*?\[/et_pb_row(?:_inner)?\]",
                               content, re.S | re.I):
        c = len(re.findall(r"\[et_pb_column\b", rowblock, re.I))
        max_cols = max(max_cols, c)
    for struct in re.findall(r'column_structure="([^"]+)"', content, re.I):
        max_cols = max(max_cols, len(struct.split(",")))
    return {"modules": counts, "n_sections": n_sections, "n_rows": n_rows, "max_cols": max_cols}


def detect_features(content):
    lc = content.lower()
    has_table = ("<table" in lc) or ("[et_pb_table" in content) or ("wp:table" in content)
    has_iframe = "<iframe" in lc
    has_embed = has_iframe or bool(re.search(r"\[(embed|et_pb_video|et_pb_code)", content, re.I)) \
        or "wp:embed" in content
    has_form = bool(re.search(r"\[(contact-form-7|wpforms|caldera_form|ninja_form|gravityform|et_pb_contact_form)",
                              content, re.I)) or "<form" in lc
    has_gallery = bool(re.search(r"\[(gallery|et_pb_gallery)", content, re.I)) or "wp:gallery" in content
    return {"table": has_table, "iframe": has_iframe, "embed": has_embed,
            "form": has_form, "gallery": has_gallery}


def collect_shortcodes(content, registered):
    found = {}
    for m in re.finditer(r"\[([a-z0-9_\-]+)(?:[\s\]\/])", content, re.I):
        sc = m.group(1)
        if sc.lower().startswith("et_pb_") or sc.lower() == "caption":
            continue
        found[sc] = True
    scs = list(found.keys())
    regset = set(registered or [])
    reg = [s for s in scs if s in regset]
    return scs, reg


def classify_target(item, engine, divi, features, cfg):
    inv = cfg["inventory"]
    slug = item["slug"]
    reasons = []
    is_curated = (item["post_type"] == "page") and (slug in inv["curated_slugs"])
    if is_curated:
        return "markdown", ["curated"], True
    if engine == "empty":
        return "markdown", ["empty content"], False
    content = item.get("content", "") or ""
    forcing = []
    if divi:
        if divi["max_cols"] >= 2:
            forcing.append("multi-column row (max=%d)" % divi["max_cols"])
        for lm in inv["layout_modules"]:
            if lm in divi["modules"]:
                forcing.append("et_pb_%s x%d" % (lm, divi["modules"][lm]))
    if engine == "gutenberg":
        for b in ("wp:columns", "wp:media-text"):
            if b in content:
                forcing.append(b)
    if features["form"]:
        forcing.append("form")
    if features["gallery"]:
        forcing.append("gallery")
    if features["table"]:
        forcing.append("table")
    if features["iframe"]:
        forcing.append("iframe/embed")
    if forcing:
        return "gutenberg", forcing, False
    reason = {"divi": "linear divi (single-col, no layout modules)",
              "gutenberg": "simple gutenberg",
              "markdown": "already markdown",
              "html": "plain html"}.get(engine, engine)
    return "markdown", [reason], False


def build_manifest(raw, cfg):
    registered = raw.get("registered_shortcodes", [])
    items_out = []
    breadcrumb_names = cfg["chrome"]["breadcrumb_shortcodes"]
    breadcrumb_count = 0
    for it in raw["items"]:
        content = it.get("content", "") or ""
        engine = detect_engine(it)
        divi = analyze_divi(content) if "[et_pb_" in content else None
        features = detect_features(content)
        scs, reg = collect_shortcodes(content, registered)
        target, reasons, curated = classify_target(it, engine, divi, features, cfg)
        if any(("[" + b) in content for b in breadcrumb_names):
            breadcrumb_count += 1
        items_out.append({
            "id": it["id"],
            "post_type": it["post_type"],
            "status": it["status"],
            "slug": it["slug"],
            "title": it["title"],
            "url_path": it.get("url_path"),
            "content_length": len(content),
            "engine": engine,
            "target": target,
            "curated": curated,
            "target_reason": reasons,
            "divi": divi,
            "features": features,
            "shortcodes": scs,
            "registered_shortcodes": reg,
        })
    summary = _summarize(items_out)
    summary["breadcrumb_shortcode_items"] = breadcrumb_count
    return {"summary": summary, "items": items_out}


def _summarize(items):
    s = {
        "generated": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "total": len(items),
        "by_type": {}, "by_engine": {}, "by_target": {},
        "by_type_engine": {}, "by_type_target": {}, "by_type_status": {},
        "curated_count": 0,
    }
    for it in items:
        t, e, g, st = it["post_type"], it["engine"], it["target"], it["status"]
        s["by_type"][t] = s["by_type"].get(t, 0) + 1
        s["by_engine"][e] = s["by_engine"].get(e, 0) + 1
        s["by_target"][g] = s["by_target"].get(g, 0) + 1
        s["by_type_engine"].setdefault(t, {})[e] = s["by_type_engine"].setdefault(t, {}).get(e, 0) + 1
        s["by_type_target"].setdefault(t, {})[g] = s["by_type_target"].setdefault(t, {}).get(g, 0) + 1
        s["by_type_status"].setdefault(t, {})[st] = s["by_type_status"].setdefault(t, {}).get(st, 0) + 1
        if it["curated"]:
            s["curated_count"] += 1
    return s


def main(argv=None):
    ap = argparse.ArgumentParser(description="Regenerate a conversion manifest from a WP DB.")
    sub = ap.add_subparsers(dest="cmd", required=True)

    p1 = sub.add_parser("gen-dump", help="print the READ-ONLY PHP dump script")
    p1.add_argument("--config", help="content-conversion.config.json")

    p2 = sub.add_parser("build", help="classify a raw dump into a conversion manifest")
    p2.add_argument("--raw", required=True, help="raw JSON produced by the dump script")
    p2.add_argument("--config", help="content-conversion.config.json")
    p2.add_argument("--out", help="output manifest path (default: stdout)")

    args = ap.parse_args(argv)
    cfg = ct_common.load_config(args.config)

    if args.cmd == "gen-dump":
        sys.stdout.write(gen_dump(cfg))
        return 0

    raw = json.load(open(args.raw, encoding="utf-8"))
    manifest = build_manifest(raw, cfg)
    out = json.dumps(manifest, ensure_ascii=False, indent=1)
    if args.out:
        open(args.out, "w", encoding="utf-8").write(out + "\n")
        sm = manifest["summary"]
        sys.stderr.write("wrote %d items -> %s\n" % (sm["total"], args.out))
        sys.stderr.write("by_engine=%s by_target=%s\n"
                         % (sm["by_engine"], sm["by_target"]))
    else:
        sys.stdout.write(out + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
